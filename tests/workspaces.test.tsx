// @vitest-environment jsdom
import React from 'react';
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { App } from '../src/App';

const base='#/coordinator?play=drive-13-row-07&seed=42';
const go=async(hash:string)=>{await act(async()=>{window.location.hash=hash;window.dispatchEvent(new HashChangeEvent('hashchange'));});};
const click=async(name:string|RegExp)=>{await act(async()=>{fireEvent.click(screen.getByRole('button',{name}));});};
beforeEach(()=>window.history.replaceState(null,'','/'+base));
afterEach(cleanup);
describe('Coordinator URL workspace',()=>{
  it('detaches a loaded official source into a persistent custom situation without changing inputs',async()=>{
    await go('#/coordinator?play=drive-10-row-10&seed=42');const view=render(<App/>);
    const values=()=>['To go','Field position','NC State score','Duke score'].map(name=>(screen.getByRole('spinbutton',{name}) as HTMLInputElement).value);
    const before=values();const field=document.querySelector('.workspace-situation')!.textContent;
    await act(async()=>{fireEvent.change(screen.getByRole('combobox',{name:'Load situation'}),{target:{value:''}});});
    expect((screen.getByRole('combobox',{name:'Load situation'}) as HTMLSelectElement).value).toBe('');
    expect(values()).toEqual(before);expect(document.querySelector('.workspace-situation')!.textContent).toBe(field);
    expect(window.location.hash).not.toContain('play=');expect(window.location.hash).not.toContain('drive=');
    expect(screen.getByText(/Custom situation · load an official/)).toBeTruthy();
    expect(screen.queryByText('Source play: drive-10-row-10')).toBeNull();
    view.unmount();render(<App/>);expect(values()).toEqual(before);
    expect((screen.getByRole('combobox',{name:'Load situation'}) as HTMLSelectElement).value).toBe('');
  });
  it('clamps URL and editor boundary inputs to playable down/distance/field position',async()=>{
    await go('#/coordinator?down=4&toGo=99&yardline=100&seed=42');render(<App/>);
    expect((screen.getByRole('spinbutton',{name:'Field position'}) as HTMLInputElement).value).toBe('99');
    expect((screen.getByRole('spinbutton',{name:'To go'}) as HTMLInputElement).value).toBe('1');
    expect(document.querySelector('.workspace-situation')!.textContent).toContain('4th & Goal · DUK 1');
    await act(async()=>{fireEvent.change(screen.getByRole('spinbutton',{name:'Field position'}),{target:{value:'0'}});});
    expect((screen.getByRole('spinbutton',{name:'Field position'}) as HTMLInputElement).value).toBe('1');
    expect(window.location.hash).toContain('yardline=1&');
    await act(async()=>{fireEvent.change(screen.getByRole('spinbutton',{name:'Field position'}),{target:{value:'100'}});});
    expect(window.location.hash).toContain('yardline=99&');expect(window.location.hash).toContain('toGo=1&');
    await go('#/coordinator?down=-1&toGo=999&yardline=0');
    expect(screen.getByRole('button',{name:'Down 1'}).getAttribute('aria-pressed')).toBe('true');
    expect((screen.getByRole('spinbutton',{name:'Field position'}) as HTMLInputElement).value).toBe('1');
    expect((screen.getByRole('spinbutton',{name:'To go'}) as HTMLInputElement).value).toBe('99');
  });
  it('recomputes on inputs, changes rankings with strategy and restores the official situation',async()=>{
    render(<App/>);
    const initial=screen.getByTestId('candidate-ranking').textContent;
    await click('conservative');
    expect(screen.getByTestId('candidate-ranking').textContent).not.toBe(initial);
    expect(screen.getByTestId('diagram-title').textContent).toContain('Punt');
    await act(async()=>{fireEvent.change(screen.getByRole('spinbutton',{name:'To go'}),{target:{value:'14'}});});
    expect(screen.getByTestId('candidate-ranking').textContent).toContain('Screen');
    expect(screen.getByText(/Custom situation: Q3/)).toBeTruthy();
    await act(async()=>{fireEvent.change(screen.getByRole('spinbutton',{name:'Field position'}),{target:{value:'85'}});});
    expect(screen.getByTestId('field-ball').getAttribute('data-yardline')).toBe('85');
    await click('Reset to official situation');
    expect((screen.getByRole('spinbutton',{name:'To go'}) as HTMLInputElement).value).toBe('1');
    expect(screen.getByTestId('field-ball').getAttribute('data-yardline')).toBe('40');
    await act(async()=>{fireEvent.change(screen.getByRole('textbox',{name:'Clock'}),{target:{value:'05:24'}});});
    expect(window.location.hash).toContain('clock=05%3A24');
  });
  it('switches the diagram to a selected alternative and reloads all URL inputs',async()=>{
    const view=render(<App/>);await click('View Quick Slant');
    expect(screen.getByTestId('diagram-title').textContent).toContain('Quick Slant');
    expect(document.querySelector('.field-player')?.getAttribute('data-concept')).toBe('Quick Slant');
    expect(screen.getByText('Selected alternative')).toBeTruthy();
    view.unmount();render(<App/>);
    expect(screen.getByTestId('diagram-title').textContent).toContain('Quick Slant');
    expect((screen.getByRole('spinbutton',{name:'To go'}) as HTMLInputElement).value).toBe('1');
    fireEvent.click(screen.getByRole('link',{name:'Simulate This Play →'}));
    await waitFor(()=>expect(screen.getByRole('heading',{name:'What-If Analysis'})).toBeTruthy());
    expect(window.location.hash).toContain('#/whatif?');
    expect(window.location.hash).toContain('candidate=Quick+Slant');
    expect(window.location.hash).toContain('seed=42');
  });
  it('loads Key Decisions on direct entry and safely normalizes invalid URL values',async()=>{
    await go('#/coordinator?down=99&toGo=-5&yardline=bad&strategy=unknown&seed=no&candidate=unknown');render(<App/>);
    expect(screen.getByTestId('field-ball').getAttribute('data-yardline')).toBe('25');
    expect((screen.getByRole('spinbutton',{name:'To go'}) as HTMLInputElement).value).toBe('1');
    await act(async()=>{fireEvent.change(screen.getByRole('combobox',{name:'Load situation'}),{target:{value:'drive-13-row-07'}});});
    expect(screen.getByText('Source play: drive-13-row-07')).toBeTruthy();
    expect(screen.getByTestId('field-ball').getAttribute('data-yardline')).toBe('40');
    fireEvent.click(screen.getByText('Model details'));
    expect(screen.getByText('betterroutes-statistical-v1')).toBeTruthy();
  });
});
describe('reproducible What-If interaction',()=>{
  it('shows capped touchdown yards consistently in the log, comparison and field overlay',async()=>{
    await go('#/whatif?play=drive-13-row-07&down=1&toGo=2&yardline=98&candidate=Inside+Zone&seed=1');render(<App/>);
    await click('Run Hypothetical Play');
    expect(document.querySelector('.simulation-log')!.textContent).toContain('+2');
    expect(document.querySelector('.comparison-table')!.textContent).toContain('+2 yd · Touchdown');
    await waitFor(()=>expect(document.querySelector('.field-callout')!.textContent).toBe('+2 YD · TOUCHDOWN'));
    expect(screen.getByTestId('simulation-result').textContent).toContain('Touchdown');
  });
  it('renders paired model-only 500-run summaries, and invalidates them when the seed changes',async()=>{
    await go('#/whatif?play=drive-13-row-07&seed=42');render(<App/>);
    await click('Run 500 simulations');
    await waitFor(()=>expect(document.querySelectorAll('.batch-table tbody tr')).toHaveLength(3),{timeout:15000});
    const rows=[...document.querySelectorAll('.batch-table tbody tr')];
    expect(new Set(rows.map(row=>row.getAttribute('data-action')))).toEqual(new Set(['RUN','PASS','PUNT']));
    const run=rows.find(row=>row.getAttribute('data-action')==='RUN')!;
    expect(run.textContent).toContain('RUN / Inside Zone');
    expect(run.textContent).toContain('ACTUAL CALL CATEGORY');
    expect(run.textContent).toContain('SELECTED ALTERNATIVE');
    expect(run.className).toBe('selected-alternative');
    expect(rows.find(row=>row.getAttribute('data-action')==='PASS')!.textContent).toContain('PASS / Quick Slant');
    expect(screen.getByText('Same category as the official call — the model does not separate concepts within a category, so their distributions match.')).toBeTruthy();
    expect(document.querySelectorAll('.position-track svg text')).toHaveLength(0);
    expect(document.querySelector('.track-key')!.textContent).toContain('S sack');
    await act(async()=>{fireEvent.change(screen.getByRole('spinbutton',{name:'Seed'}),{target:{value:'1'}});});
    expect(document.querySelector('.batch-table')).toBeNull();
  },20000);
  it('includes a legal FG category and marks a different selected category without a same-category note',async()=>{
    await go('#/whatif?play=drive-13-row-07&yardline=60&candidate=Quick+Slant&seed=42');render(<App/>);
    await click('Run 500 simulations');
    await waitFor(()=>expect(document.querySelectorAll('.batch-table tbody tr')).toHaveLength(4),{timeout:15000});
    const rows=[...document.querySelectorAll('.batch-table tbody tr')];
    expect(new Set(rows.map(row=>row.getAttribute('data-action')))).toEqual(new Set(['RUN','PASS','PUNT','FIELD_GOAL']));
    expect(document.querySelector('.batch-table .selected-alternative')!.getAttribute('data-action')).toBe('PASS');
    expect(rows.find(row=>row.getAttribute('data-action')==='RUN')!.textContent).toContain('ACTUAL CALL CATEGORY');
    expect(screen.queryByText(/Same category as the official call/)).toBeNull();
    await go('#/whatif?play=drive-13-row-07&down=1&seed=42');
    expect(document.querySelector('.batch-table')).toBeNull();
    await click('Run 500 simulations');
    await waitFor(()=>expect(document.querySelectorAll('.batch-table tbody tr')).toHaveLength(2),{timeout:15000});
    expect(new Set([...document.querySelectorAll('.batch-table tbody tr')].map(row=>row.getAttribute('data-action')))).toEqual(new Set(['RUN','PASS']));
  },20000);
  it('runs, continues, resets, replays the same sequence and restores it from the URL',async()=>{
    await go('#/whatif?play=drive-13-row-07&seed=42');const view=render(<App/>);
    expect(screen.getByRole('button',{name:'Continue Drive'}).hasAttribute('disabled')).toBe(true);
    expect(screen.getByRole('button',{name:'Replay sequence'}).hasAttribute('disabled')).toBe(true);
    await click('Run Hypothetical Play');
    expect(screen.getByRole('button',{name:'Run Hypothetical Play'}).hasAttribute('disabled')).toBe(true);
    expect(screen.getByTestId('simulation-result').textContent).toContain('1 plays');
    expect(screen.getByRole('button',{name:'Continue Drive'}).hasAttribute('disabled')).toBe(false);
    await click('Continue Drive');
    expect(screen.getByTestId('simulation-result').textContent).toContain('2 plays');
    await click('Sim to End');
    expect(screen.getByTestId('simulation-result').textContent).toContain('Punt');
    expect(screen.getByRole('button',{name:'Continue Drive'}).hasAttribute('disabled')).toBe(true);
    const log=document.querySelector('.simulation-log')!.textContent;
    const result=screen.getByTestId('simulation-result').textContent;
    await click('Replay sequence');
    expect(screen.getByText('Replaying same sampled sequence')).toBeTruthy();
    expect(document.querySelector('.simulation-log')!.textContent).toBe(log);
    view.unmount();render(<App/>);
    expect(document.querySelector('.simulation-log')!.textContent).toBe(log);
    expect(screen.getByTestId('simulation-result').textContent).toBe(result);
    await click('Reset simulation');
    expect(screen.getByTestId('simulation-result').textContent).toContain('0 plays');
    await click('Sim to End');
    expect(document.querySelector('.simulation-log')!.textContent).toBe(log);
    expect(document.querySelector('.comparison-table')!.textContent).toContain('rush / Gause');
    expect(document.querySelector('.comparison-table')!.textContent).toContain('Inside Zone');
    expect(document.querySelector('.comparison-table')!.textContent).toContain('+5');
  });
  it('seed changes clear the result and reproduce exactly; new seed is URL-backed',async()=>{
    await go('#/whatif?play=drive-13-row-07&seed=42');render(<App/>);
    await click('Sim to End');const old=document.querySelector('.simulation-log')!.textContent;
    await act(async()=>{fireEvent.change(screen.getByRole('spinbutton',{name:'Seed'}),{target:{value:'1'}});});
    expect(screen.getByTestId('simulation-result').textContent).toContain('0 plays');
    await click('Sim to End');expect(document.querySelector('.simulation-log')!.textContent).not.toBe(old);
    expect(screen.getByTestId('simulation-result').textContent).toContain('Turnover');
    await act(async()=>{fireEvent.change(screen.getByRole('spinbutton',{name:'Seed'}),{target:{value:'42'}});});
    await click('Sim to End');expect(document.querySelector('.simulation-log')!.textContent).toBe(old);
    await click('New seed');
    expect(window.location.hash).toContain('seed=');
    expect(screen.getByTestId('simulation-result').textContent).toContain('0 plays');
  });
  it('handles no historical source, custom mismatches and corrupt URL state honestly',async()=>{
    await go('#/whatif?seed=NaN&candidate=not-a-play&steps=-1');render(<App/>);
    expect(screen.getByText(/No official source selected/)).toBeTruthy();
    expect(screen.getByTestId('simulation-result').textContent).toContain('Not run');
    await click('Run Hypothetical Play');
    expect(screen.getByTestId('simulation-result').textContent).toContain('1 plays');
    await go('#/whatif?play=drive-13-row-07&yardline=70');
    expect(screen.getByText(/Custom starting situation:/)).toBeTruthy();
  });
});
